// Copies everything in src/content into D1 as the starting data.
// Writes migrations/0002_seed.sql. Rows that already exist are left alone (INSERT OR IGNORE),
// so this is safe to apply more than once and never overwrites edits made in the admin.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
const now = new Date().toISOString();
const files = walk('seed/content').filter((f) => /\.(md|json)$/.test(f)).sort();
const sql = files.map((f) => `INSERT OR IGNORE INTO content (path, body, version, updated_at, updated_by) VALUES (${q('src/content/' + f.replace(/\\/g, '/').replace(/^seed\/content\//, ''))}, ${q(readFileSync(f, 'utf8'))}, 1, ${q(now)}, 'seed');`).join('\n');
writeFileSync('migrations/0002_seed.sql', '-- Generated by scripts/seed-d1.mjs\n' + sql + '\n');
console.log(`Seeded ${files.length} items into migrations/0002_seed.sql`);
